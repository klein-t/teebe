#!/usr/bin/env node
// Golden fixtures for the Swift port of the thinking-orbs geometry
// (thinking-orbs 0.3.2, MIT © 2026 Jakub Antalik).
//
// Runs the package's real engine and emits the frames the app draws, so the
// tests in Tests/TeebeCoreTests/ThinkingOrbTests.swift can compare numbers.
//
// Regenerate (node_modules never enters the repo):
//   cd /tmp && npm pack thinking-orbs@0.3.2 && tar -xzf thinking-orbs-0.3.2.tgz
//   node scripts/thinking-orb-fixtures.mjs /tmp/package \
//     > Tests/TeebeCoreTests/ThinkingOrbFixtures.swift
import { readdirSync } from 'node:fs';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';

const pkg = process.argv[2];
if (!pkg) {
  console.error('usage: node scripts/thinking-orb-fixtures.mjs <unpacked thinking-orbs package dir>');
  process.exit(1);
}
// The engine chunk carries a content hash in its name; its exports are
// minified aliases: r = resolvePreset, a = scaleRadii, M = MODE_FRAMES.
const dist = join(pkg, 'dist');
const chunk = readdirSync(dist).find((f) => /^index-.*\.js$/.test(f));
const engine = await import(pathToFileURL(join(dist, chunk)).href);
const resolvePreset = engine.r;
const scaleRadii = engine.a;
const MODE_FRAMES = engine.M;

// What the app renders: size 20, dotSize 1.2, default dots and speed.
// Mirrors ThinkingOrb's option pipeline in dist/index.es.js.
const SIZE = 20;
const DOT_SIZE = 1.2;
const TIMES = [0, 0.6, 1.3, 3.7, 5.05, 7.1, 9.9, 12.5, 25.3, 101.7];

const out = { size: SIZE, dotSize: DOT_SIZE, states: {} };
for (const state of ['solving', 'breathing']) {
  const { mode, speed, opts: preset } = resolvePreset(state, SIZE);
  const opts = scaleRadii(preset, DOT_SIZE);
  const frames = TIMES.map((t) => {
    const frame = MODE_FRAMES[mode](SIZE, t, opts);
    return { t, dots: frame.dots.map((d) => [d.x, d.y, d.z, d.r, d.white, d.a ?? 1]) };
  });
  out.states[state] = { mode, speed, frames };
}

const json = JSON.stringify(out);
process.stdout.write(`// Generated by scripts/thinking-orb-fixtures.mjs from thinking-orbs 0.3.2
// (MIT © 2026 Jakub Antalik). Do not edit; regenerate with that script.
// Each dot is [x, y, z, r, white, alpha], in draw order.

enum ThinkingOrbFixtures {
    static let json = #"${json}"#
}
`);
